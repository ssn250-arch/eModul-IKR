import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from '/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript/lib/typescript.js';
const jsx=fs.readFileSync('src/MotherboardExplorer.jsx','utf8');
const css=fs.readFileSync('src/MotherboardExplorer.css','utf8');
const parsed=ts.createSourceFile('MotherboardExplorer.jsx',jsx,ts.ScriptTarget.Latest,true,ts.ScriptKind.JSX);
assert.equal(parsed.parseDiagnostics.length,0,'Valid JSX required');
assert.match(jsx,/className="mbx-quiz-target"/,'Target marker must exist');
