assert.match(css,/\.mbx-modal-map\{position:relative/,'Image and marker must share a scaled coordinate plane');
assert.match(css,/@media\(max-width:640px\)/,'Small-screen media rules');
const questions=jsx.match(/const QUESTIONS = \[([\s\S]*?)\];/)?.[1]||'';
assert.equal((questions.match(/\{tab:/g)||[]).length,6,'Keep 6 questions');
console.log('PASS v2.3: yellow hollow target, explanatory legend, fullscreen marker, responsive CSS, JSX and six questions.');
